/**
 * Remove plugin `.bin` directories before packaging.
 *
 * A plugin's node_modules/.bin holds CLI shims for its dependencies — nothing
 * a packaged Puffin ever runs. On Windows npm writes them as symlinks, and one
 * of them (stats-plugin's loose-envify) is a reparse point Node cannot even
 * lstat: `npm run package` died with EACCES before it copied a single file.
 *
 * The failure comes from electron-builder's dependency scan, which walks the
 * tree before any `files`/`extraResources` filter applies — so there is no
 * config that can exclude it. Deleting the shims is the fix, and it costs
 * nothing, because they are regenerated by an npm install inside the plugin
 * and are useless at runtime either way.
 *
 * Run automatically by `npm run package` via the prepackage hook.
 */

import { readdirSync, rmSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pluginsDir = join(root, 'plugins')

if (!existsSync(pluginsDir)) process.exit(0)

let removed = 0
for (const entry of readdirSync(pluginsDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const binDir = join(pluginsDir, entry.name, 'node_modules', '.bin')
  if (!existsSync(binDir)) continue
  rmSync(binDir, { recursive: true, force: true })
  console.log(`[clean-plugin-bins] removed ${entry.name}/node_modules/.bin`)
  removed++
}

console.log(`[clean-plugin-bins] ${removed} shim director${removed === 1 ? 'y' : 'ies'} removed`)
